def build_parser():
    p = argparse.ArgumentParser(
        prog="safety_report_builder.py",
        description="安全三同时报告编制工具：报告骨架 / 危险有害因素辨识 / 验收资料清单 / LEC 计算",
        epilog="示例：python3 safety_report_builder.py outline --type 安全设施设计专篇 --project \"某某污水处理厂\"",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = p.add_subparsers(dest="command", metavar="{outline,hazard-list,checklist,lec-calc}")

    p1 = sub.add_parser("outline", help="生成报告/专篇 Markdown 章节骨架")
    p1.add_argument("--type", required=True, choices=list(OUTLINES.keys()),
                    help="报告类型：" + " / ".join(OUTLINES.keys()))
    p1.add_argument("--project", default="", help="项目名称")
    p1.add_argument("--out", default="", help="输出文件路径（缺省打印到终端）")
    p1.set_defaults(func=cmd_outline)

    p2 = sub.add_parser("hazard-list", help="生成危险有害因素辨识表")
    p2.add_argument("--project-type", required=True, choices=list(HAZARDS.keys()),
                    dest="project_type", help="项目类型：污水厂 / 管网 / 泵站")
    p2.add_argument("--stage", default="全部", help="工艺环节，如 生化池、有限空间、施工阶段")
    p2.add_argument("--out", default="", help="输出文件路径（缺省打印到终端）")
    p2.set_defaults(func=cmd_hazard_list)

    p3 = sub.add_parser("checklist", help="输出安全三同时验收资料清单（26 项）")
    p3.add_argument("--out", default="", help="输出文件路径（缺省打印到终端）")
    p3.set_defaults(func=cmd_checklist)

    p4 = sub.add_parser("lec-calc", help="LEC 法危险性计算 D = L × E × C")
    p4.add_argument("--l", type=float, required=True, help="L 事故发生的可能性")
    p4.add_argument("--e", type=float, required=True, help="E 暴露于危险环境的频繁程度")
    p4.add_argument("--c", type=float, required=True, help="C 发生事故产生的后果")
    p4.add_argument("--out", default="", help="输出文件路径（缺省打印到终端）")
    p4.set_defaults(func=cmd_lec_calc)

    return p


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "func", None):
        parser.print_help()
        return 1
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
