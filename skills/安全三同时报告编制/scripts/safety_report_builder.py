def _emit(text, out):
    if out:
        p = Path(out)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print("已写入：%s" % p)
    else:
        sys.stdout.write(text)
        if not text.endswith("\n"):
            sys.stdout.write("\n")


def cmd_outline(args):
    rtype = args.type
    if rtype not in OUTLINES:
        print("错误：未知报告类型 '%s'。" % rtype, file=sys.stderr)
        print("可选值：" + "、".join(OUTLINES.keys()), file=sys.stderr)
        return 2
    project = args.project or "【待填：项目名称】"
    lines = []
    lines.append("# %s" % rtype)
    lines.append("")
    lines.append("- 项目名称：%s" % project)
    lines.append("- 报告类型：%s" % rtype)
    lines.append("- 建设单位：【待填：建设单位全称】")
    lines.append("- 编制单位：【待填：编制单位全称及资质证书编号】")
    lines.append("- 编制日期：【待填：YYYY 年 MM 月 DD 日】")
    lines.append("")
    lines.append("> 占位符统一采用【待填：xxx】格式；定稿前须逐项替换，残留占位符视为不合格。")
    lines.append("")
    n_ch = 0
    for title, subs in OUTLINES[rtype]:
        lines.append("## %s" % title)
        lines.append("")
        for s in subs:
            lines.append("- %s" % s)
            n_ch += 1
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("章节数：%d　条目数：%d" % (len(OUTLINES[rtype]), n_ch))
    _emit("\n".join(lines), args.out)
    return 0


def cmd_hazard_list(args):
    ptype = args.project_type
    if ptype not in HAZARDS:
        print("错误：未知项目类型 '%s'。" % ptype, file=sys.stderr)
        print("可选值：" + "、".join(HAZARDS.keys()), file=sys.stderr)
        return 2
    stage = args.stage or "全部"
    groups = HAZARDS[ptype]
    if stage in ("全部", "所有", "all"):
        selected = list(groups.items())
    else:
        selected = [(k, v) for k, v in groups.items() if stage in k or k in stage]
        if not selected:
            matched = False
            for k, rows in groups.items():
                hit = [r for r in rows if stage in r[1] or stage in r[0]]
                if hit:
                    selected.append((k, hit))
                    matched = True
            if not matched:
                print("提示：未匹配到工艺环节 '%s'，已输出 %s 全部辨识项。"
                      % (stage, ptype), file=sys.stderr)
                selected = list(groups.items())

    lines = []
    lines.append("# %s 危险有害因素辨识表" % ptype)
    lines.append("")
    lines.append("- 项目类型：%s" % ptype)
    lines.append("- 工艺环节：%s" % stage)
    lines.append("- 辨识依据：GB 6441-1986、GB/T 13861-2022、应急管理部令第 13 号")
    lines.append("")
    total = 0
    for gname, rows in selected:
        lines.append("## %s" % gname)
        lines.append("")
        lines.append("| 序号 | 危害源 | 所在部位 | 可能后果 | 防护措施 | 依据标准 |")
        lines.append("|------|--------|----------|----------|----------|----------|")
        for i, (src, loc, cons, meas, std) in enumerate(rows, 1):
            lines.append("| %d | %s | %s | %s | %s | %s |"
                         % (i, src, loc, cons, meas, std))
            total += 1
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("合计辨识项：%d 项" % total)
    _emit("\n".join(lines), args.out)
    return 0


def cmd_checklist(args):
    lines = []
    lines.append("# 安全三同时验收资料清单（26 项）")
    lines.append("")
    lines.append("| 序号 | 资料名称 | 份数 | 是否必备 | 备注 |")
    lines.append("|------|----------|------|----------|------|")
    for no, name, cnt, need, note in CHECKLIST:
        lines.append("| %d | %s | %s | %s | %s |" % (no, name, cnt, need, note))
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("清单合计：%d 项，其中必备 %d 项。"
                 % (len(CHECKLIST), sum(1 for c in CHECKLIST if c[3] == "必备")))
    lines.append("")
    lines.append("核查口径：全部 26 项须逐项核对；任一项缺失、过期或未签章即判定为资料不完整，")
    lines.append("不得进入安全设施竣工验收程序。")
    _emit("\n".join(lines), args.out)
    return 0


def cmd_lec_calc(args):
    L, E, C = args.l, args.e, args.c
    if L <= 0 or E <= 0 or C <= 0:
        print("错误：L、E、C 均须大于 0。", file=sys.stderr)
        return 2
    D = L * E * C
    name, action = lec_grade(D)
    lines = []
    lines.append("# LEC 作业条件危险性评价结果")
    lines.append("")
    lines.append("- L（事故发生的可能性）：%s" % L)
    lines.append("- E（暴露于危险环境的频繁程度）：%s" % E)
    lines.append("- C（发生事故产生的后果）：%s" % C)
    lines.append("- 危险性 D = L × E × C = %.2f" % D)
    lines.append("- 危险等级：%s" % name)
    lines.append("- 处置要求：%s" % action)
    lines.append("")
    lines.append("## 取值参照表")
    lines.append("")
    lines.append("| 参数 | 取值 | 含义 |")
    lines.append("|------|------|------|")
    for pname, items in LEC_TABLE:
        for i, (val, meaning) in enumerate(items):
            lines.append("| %s | %s | %s |" % (pname if i == 0 else "", val, meaning))
    lines.append("")
    lines.append("## 分级判据")
    lines.append("")
    lines.append("| D 值区间 | 危险程度 | 处置要求 |")
    lines.append("|----------|----------|----------|")
    lines.append("| > 320 | A 级（极其危险） | 不能继续作业 |")
    lines.append("| 160 ~ 320 | B 级（高度危险） | 须立即整改 |")
    lines.append("| 70 ~ 160 | C 级（显著危险） | 须限期整改 |")
    lines.append("| 20 ~ 70 | D 级（一般危险） | 须加强监测 |")
    lines.append("| < 20 | E 级（稍有危险） | 可以接受 |")
    _emit("\n".join(lines), args.out)
    return 0


