#!/usr/bin/env python3
"""狗头军师 · 消息拆解
把对方发来的消息/对话按「字面 / 潜台词 / 信号温度 / 需求 / 军师点评」结构化解读。
规则驱动，纯标准库，输出供人工复核。
"""
import argparse, re, sys

# 句式规则：(正则, 温度, 确定性, 情绪, 需求, 可能含义列表)
RULES = [
    (r"^(嗯+|哦+|恩|好的|好哒|好|ok|okay|行|收到)[。.!~]*$", "中", "模糊", "中性", "客套",
     ["简短收束，可能不想展开", "也可能只是随手回复，看后续节奏"]),
    (r"(随便你|都行|你决定|听你的)", "中低", "回避", "中性偏淡", "交付决定",
     ["把决定权给你，或已疲惫不想再讨论", "若连续出现，多为热情下滑信号"]),
    (r"(我累了|改天吧|再说吧|以后再说|有空聊)", "中低", "回避", "中性", "求空间",
     ["真的累/忙", "也可能在回避当下话题"]),
    (r"(你想多了|你多心了|没有的事|哪有)", "中", "否认", "中性或防御", "降温",
     ["否认过度解读", "也可能在回避不愿展开的问题"]),
    (r"(你最近.{0,4}(忙|怎么样|还好吗)|在忙什么)", "中高", "试探", "中性", "试探距离",
     ["轻度主动，试探你的近况", "也可能是为疏远铺垫"]),
    (r"(做朋友|还是朋友|朋友挺好)", "低", "明确", "中性偏负", "降级关系",
     ["明确将关系降级", "需认真对待，不建议硬推"]),
    (r"(别对我这么好|别这样|我不值得)", "中低", "划界", "负向或愧疚", "划边界",
     ["在划边界", "或自我价值感低，需区分"]),
    (r"(对不起|抱歉|是我不对|我错了)", "中高", "明确", "负向/求和", "求和",
     ["主动求和信号", "看后续是否有行动配合"]),
    (r"(想你了|在干嘛|睡了吗|吃了吗)", "高", "主动", "正向", "邀约/亲近",
     ["主动亲近信号", "回应温度是关系热度计"]),
    (r"(呵呵|随你便|不用了|算了)", "低", "负向", "抵触", "拒绝沟通",
     ["负向信号，情绪可能已累积", "此刻不宜追问，宜给空间"]),
]

TEMP_RANK = {"高": 4, "中高": 3, "中": 2, "中低": 1, "低": 0}


def decode(text):
    hits = []
    for pat, temp, cert, emo, need, hints in RULES:
        if re.search(pat, text, re.I):
            hits.append({"句式": pat, "温度": temp, "确定性": cert,
                         "情绪": emo, "需求": need, "可能含义": hints})
    return hits


def main():
    ap = argparse.ArgumentParser(description="拆解消息的字面/潜台词/信号与需求")
    ap.add_argument("--text", help="对方发来的消息文本")
    ap.add_argument("--file", help="从文件读取消息（一行一条）")
    args = ap.parse_args()

    if not args.text and not args.file:
        ap.error("请提供 --text 或 --file")
    text = args.text or open(args.file, encoding="utf-8", errors="ignore").read()

    hits = decode(text)
    print("=" * 56)
    print("狗头军师 · 消息拆解")
    print("=" * 56)
    print(f"\n【原文】{text.strip()[:200]}")

    if not hits:
        print("\n【信号】未命中常见句式，多为普通陈述。")
        print("军师点评：信息不足，先别急着解读。给一次低风险回应，看对方节奏再判断。")
        return

    temps = [h["温度"] for h in hits]
    best = max(temps, key=lambda t: TEMP_RANK.get(t, 2))
    print(f"\n【综合温度】{best}（命中 {len(hits)} 类句式）")
    for h in hits:
        print(f"\n· 句式匹配：{h['句式']}")
        print(f"  温度 {h['温度']} / 确定性 {h['确定性']} / 情绪 {h['情绪']} / 需求 {h['需求']}")
        for m in h["可能含义"]:
            print(f"  - 可能：{m}（待确认）")

    print("\n【军师点评】")
    if TEMP_RANK.get(best, 2) >= 3:
        print("  温度偏高，但别一口气扑上去。接住、回应一条、把节奏交回去。")
    elif TEMP_RANK.get(best, 2) <= 1:
        print("  温度偏低，此刻追问或长篇解释都会加压。给空间，等对方主动一次。")
    else:
        print("  温度中性，属于可进可退。一次简短、无压力的日常回应即可，别带情绪。")
    print("\n提醒：以上为概率判读，非定论。关系阶段与上下文会改变含义。")


if __name__ == "__main__":
    main()
